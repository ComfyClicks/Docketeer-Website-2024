import {createRequire} from 'node:module';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require('/Users/andywhite/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const results={date:new Date().toISOString(),url:'http://127.0.0.1:4173/',browser:browser.version()};
try {
 const page=await browser.newPage({viewport:{width:1440,height:900},reducedMotion:'no-preference'});
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 await page.addInitScript(()=>{window.__frameCount=0;const raf=window.requestAnimationFrame.bind(window);window.requestAnimationFrame=cb=>raf(time=>{window.__frameCount++;cb(time)});});
 await page.goto(results.url,{waitUntil:'networkidle'});
 const count=()=>page.evaluate(()=>window.__frameCount);
 const button=page.locator('#background-motion');
 assert.equal(await button.textContent(),'Play background animation');
 const initial=await count();await page.waitForTimeout(300);assert.equal(await count(),initial);
 await button.click();await page.waitForTimeout(300);const playing=await count();assert(playing>initial);
 assert.equal(await button.textContent(),'Pause background animation');
 await page.emulateMedia({reducedMotion:'reduce'});await page.waitForTimeout(150);const stopped=await count();await page.waitForTimeout(300);assert.equal(await count(),stopped);assert(await button.isDisabled());
 await page.emulateMedia({reducedMotion:'no-preference'});await page.waitForTimeout(150);assert.equal(await button.textContent(),'Play background animation');assert(!(await button.isDisabled()));
 results.motion={passed:true,initialFrames:initial,playingFrames:playing,stoppedFrames:stopped,errors};assert.equal(errors.length,0);
 const fallback=await browser.newPage({viewport:{width:390,height:844}});
 const fallbackErrors=[];fallback.on('pageerror',e=>fallbackErrors.push(String(e)));
 await fallback.addInitScript(()=>{const get=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){if(type==='webgl2')return null;return get.call(this,type,...args)};});
 await fallback.goto(results.url,{waitUntil:'networkidle'});
 assert(await fallback.locator('#background-motion').isHidden());assert(await fallback.getByRole('heading',{level:1}).isVisible());
 const background=await fallback.evaluate(()=>getComputedStyle(document.body).backgroundColor);assert.equal(background,'rgb(0, 0, 5)');assert.equal(fallbackErrors.length,0);
 results.webglUnavailable={passed:true,background,errors:fallbackErrors};
 results.limitations=['Animated GIF media is unchanged and may continue moving with reduced motion.','Frame instrumentation measures requestAnimationFrame callbacks, not GPU activity.','No physical device, screen reader, or real browser zoom tested.'];
 fs.writeFileSync('docs/modernization/phase-c/motion-results.json',JSON.stringify(results,null,2));console.log(JSON.stringify(results,null,2));
} finally {await browser.close()}
